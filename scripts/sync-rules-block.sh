#!/bin/bash
# Copies shared/findings-and-rounds.md into the agent files between their marker lines.
# Everything outside the markers stays byte-identical; running it twice changes nothing.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
src=shared/findings-and-rounds.md
begin='<!-- BEGIN findings-and-rounds (generated by scripts/sync-rules-block.sh from shared/findings-and-rounds.md; edit the source) -->'
end='<!-- END findings-and-rounds -->'

[ -s "$src" ] || { echo "sync-rules-block: $src missing or empty" >&2; exit 1; }
# Optional arguments: agent files to sync (default: the three reviewers).
if [ "$#" -gt 0 ]; then files=("$@"); else files=(plugins/ordo/agents/code-reviewer.md plugins/ordo/agents/qa.md plugins/ordo/agents/po.md); fi
for f in "${files[@]}"; do
  nb=$(grep -cxF -- "$begin" "$f" || true); ne=$(grep -cxF -- "$end" "$f" || true)
  if [ "$nb" != 1 ] || [ "$ne" != 1 ]; then
    echo "sync-rules-block: $f needs exactly one marker pair, found $nb begin and $ne end" >&2; exit 1
  fi
  lb=$(grep -nxF -- "$begin" "$f" | cut -d: -f1); le=$(grep -nxF -- "$end" "$f" | cut -d: -f1)
  if [ "$lb" -ge "$le" ]; then echo "sync-rules-block: $f has the END marker before the BEGIN marker" >&2; exit 1; fi
  tmp=$(mktemp)
  awk -v b="$begin" -v e="$end" -v s="$src" '
    $0==b { print; while ((getline line < s) > 0) print line; close(s); skip=1; next }
    $0==e { skip=0 }
    !skip { print }
    END { if (skip) exit 1 }
  ' "$f" > "$tmp" || { rm -f "$tmp"; echo "sync-rules-block: $f ends inside the marked block" >&2; exit 1; }
  cat "$tmp" > "$f"   # keep the file mode
  rm -f "$tmp"
done
